"""Causal, backprop-free scalar shrinkage and uncertainty veto for Dust gains.

The head forecast is generated by LFM3's external historical/activation
attention. This gate never touches model weights; it learns a single
nonnegative shrinkage coefficient in [0,1] from *PRIOR EPISODES ONLY*.

A finite ridge-regularized least-squares solution is recomputed from earlier
(train-only preprobe prediction, measured gain) pairs, not backpropagation.
It abstains unless confidence, simple zero-baseline skill and historical
episode coverage jointly pass. Abstention never grants optimizer authority.
"""
from __future__ import annotations

import math

SCHEMA = "sensorgraft.lfm3.dust-uncertainty-gate.v1"
RIDGE = 0.01
MIN_PRIOR_EPISODES = 4
MIN_RELATIVE_MSE_BENEFIT = .05
BOUND_SIGMA = 2.0
PROBES_PER_EPISODE = 8


def _number(x):
    return type(x) in (int, float) and math.isfinite(x) and abs(x) <= 100.


class CausalShrinkageGate:
    """One head, registered train-only episode losses and guarded selection."""

    def __init__(self):
        self._past: list[tuple[float, float]] = []
        self._prior_episodes = 0
        self._last_episode = -1

    @property
    def episodes(self):
        return self._prior_episodes

    @property
    def size(self):
        return len(self._past)

    @property
    def coefficient(self):
        if not self._past:
            return 0.0
        numerator = sum(p * y for p, y in self._past)
        denominator = RIDGE + sum(p * p for p, _ in self._past)
        return max(0., min(1., numerator / denominator))

    @property
    def zero_mse(self):
        if not self._past:
            return 0.
        return sum(y*y for _, y in self._past) / len(self._past)

    @property
    def calibrated_training_mse(self):
        # Diagnostic optimistic fit of the current past-only coefficient.
        # Do not substitute this for a prospective prequential score.
        if not self._past:
            return 0.
        c = self.coefficient
        return sum((c*p-y)**2 for p,y in self._past) / len(self._past)

    def predict(self, raw_prediction, *, episode):
        if (not _number(raw_prediction) or type(episode) is not int
                or episode < 0 or episode < self._prior_episodes):
            raise ValueError("invalid_or_stale_causal_prediction")
        alpha = self.coefficient
        prediction = alpha * float(raw_prediction)
        noise = math.sqrt(self.calibrated_training_mse)
        # Negative upper bounds do not imply zero actual gain; this is a
        # safety-oriented heuristic, not a valid calibrated confidence interval.
        lower_bound = prediction - BOUND_SIGMA * noise
        zero = self.zero_mse
        skill = bool(
            self._prior_episodes >= MIN_PRIOR_EPISODES and
            zero > 0 and self.calibrated_training_mse < zero * (1-MIN_RELATIVE_MSE_BENEFIT)
        )
        proposal = bool(skill and prediction > 0 and lower_bound > 0)
        return {
            "raw_prediction": float(raw_prediction),
            "predicted_gain": prediction,
            "shrinkage_coefficient": alpha,
            "noise_rms": noise,
            "conservative_lower_bound": lower_bound,
            "prior_training_episodes": self._prior_episodes,
            "prior_scalar_observations": len(self._past),
            "historical_skill_gate": skill,
            "eligible_to_probe": proposal,
            "optimizer_switch_permitted": False,
            "weight_update_permitted": False,
        }

    def observe_episode(self, forecast_and_gains, *, episode, split="train", measured=False):
        if (split != "train" or measured is not True or type(episode) is not int
                or episode != self._prior_episodes
                or not isinstance(forecast_and_gains, list)
                or len(forecast_and_gains) != PROBES_PER_EPISODE
                or any(type(row) not in (tuple,list) or len(row)!=2
                       or not _number(row[0]) or not _number(row[1])
                       for row in forecast_and_gains)):
            raise ValueError("untrusted_or_out_of_order_forward_feedback")
        self._past.extend((float(p),float(y)) for p,y in forecast_and_gains)
        self._prior_episodes += 1
        self._last_episode = episode
        return {
            "memory_count": len(self._past),
            "episodes": self._prior_episodes,
            "shrinkage_coefficient": self.coefficient,
            "backward_calls": 0,
            "weight_promotion_permitted": False,
        }
